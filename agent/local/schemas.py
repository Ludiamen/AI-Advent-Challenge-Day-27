"""JSON-схемы ответов локальных моделей (День 27).

Ollama принимает в поле format JSON-схему и ограничивает генерацию ею: модель
физически не может написать текст вокруг JSON, забыть кавычку или поле.
Облачным моделям хватает просьбы в промпте, а маленькой локальной — нет: без
схемы qwen3 на «верни только JSON» то и дело начинает с рассуждения. Проба
Дня 27 показала, что кириллические имена полей в схеме работают.

Схема — не проверка смысла: «вопрос_для_поиска», переписанный из инструкции,
схеме удовлетворяет. Смысл по-прежнему проверяет код (цитаты — citecheck,
числа ответа по памяти — chat.py).

Какая схема у какой роли, записано в карте ролей (local-roles.json, поле
«схема»); формат(роль, ключ) отдаёт схему только локальной модели, а
температура(роль, ключ) — температуру роли из той же карты.
"""

from __future__ import annotations

from typing import Any

from agent import catalog

_СТРОКИ = {"type": "array", "items": {"type": "string"}}

РАЗБОР = {
    "type": "object",
    "properties": {
        "вид": {"type": "string", "enum": ["документы", "разговор"]},
        "вопрос_для_поиска": {"type": "string"},
        "подвопросы": _СТРОКИ,
        "цель": {"type": "string"},
        "смена_цели": {"type": "boolean"},
        "уточнения": _СТРОКИ,
        "ограничения": _СТРОКИ,
        "термины": {"type": "array", "items": {
            "type": "object",
            "properties": {"термин": {"type": "string"}, "значение": {"type": "string"}},
            "required": ["термин", "значение"]}},
    },
    "required": ["вид", "вопрос_для_поиска", "подвопросы", "цель", "смена_цели",
                 "уточнения", "ограничения", "термины"],
}

ЦИТАТЫ = {
    "type": "object",
    "properties": {
        "ответ": {"type": "string"},
        "источники": {"type": "array", "items": {"type": "integer"}},
        "цитаты": {"type": "array", "items": {
            "type": "object",
            "properties": {"n": {"type": "integer"}, "текст": {"type": "string"}},
            "required": ["n", "текст"]}},
        "не_знаю": {"type": "boolean"},
        "неоднозначно": {"type": "boolean"},
        "уточнение": {"type": "string"},
    },
    "required": ["ответ", "источники", "цитаты", "не_знаю", "уточнение"],
}

ПО_ПАМЯТИ = {
    "type": "object",
    "properties": {"ответ": {"type": "string"}, "опора": _СТРОКИ},
    "required": ["ответ", "опора"],
}

СХЕМЫ: dict[str, dict[str, Any]] = {"разбор": РАЗБОР, "цитаты": ЦИТАТЫ, "по_памяти": ПО_ПАМЯТИ}


def формат(роль: str, ключ: str, схема: str = "") -> dict[str, Any] | None:
    """Схема ответа для вызова: только локальной модели и только если она есть.

    схема — имя явно (у роли «ответ-по-документам» две схемы: цитаты и ответ
    по памяти); пусто — из карты ролей."""
    if not ключ or ключ not in catalog.MODELS or not catalog.get(ключ).local:
        return None
    if not схема:
        from agent.local import offline
        схема = offline.параметры_роли(роль).схема
    return СХЕМЫ.get(схема)


def температура(роль: str, ключ: str) -> float | None:
    """Температура роли из карты — только для локальной модели.

    Ответ RAG (answer.py, abstain.py) шёл при температуре клиента по умолчанию
    (0,2), хотя карта объявляла для ответа 0: это вскрыл прогон сравнения
    Дня 28 (низкая дословная устойчивость локальной 4B), исправление перенесено
    в День 27. Облачным моделям карта не указ: None — температура клиента."""
    if not ключ or ключ not in catalog.MODELS or not catalog.get(ключ).local:
        return None
    from agent.local import offline
    return offline.параметры_роли(роль).температура
